// navigator.clipboard.writeText needs a secure context (fine on localhost/
// HTTPS) and can still be blocked by permissions in some embedded/older
// browser contexts — the execCommand fallback covers those, matching how
// Zoom/Meet's own "copy link" buttons stay resilient across browsers.
export async function copyToClipboard(text) {
  if (navigator.clipboard?.writeText) {
    try {
      await navigator.clipboard.writeText(text);
      return true;
    } catch {
      // fall through to the legacy path below
    }
  }
  try {
    const textarea = document.createElement("textarea");
    textarea.value = text;
    textarea.style.position = "fixed";
    textarea.style.opacity = "0";
    document.body.appendChild(textarea);
    textarea.focus();
    textarea.select();
    const ok = document.execCommand("copy");
    document.body.removeChild(textarea);
    return ok;
  } catch {
    return false;
  }
}
